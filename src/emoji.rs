#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_common_codes() {
        assert_eq!(lookup("smile"), Some("😄"));
        assert_eq!(lookup("heart"), Some("❤️"));
        assert_eq!(lookup("rocket"), Some("🚀"));
    }

    #[test]
    fn expands_colon_token() {
        assert_eq!(expand(":smile:"), "😄");
        assert_eq!(expand(":unknown:"), ":unknown:");
    }

    #[test]
    fn unknown_code_passes_through() {
        assert_eq!(expand("::"), "::");
        assert_eq!(expand(":foo:"), ":foo:");
    }
}
