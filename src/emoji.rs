//! A dependency-free map of common GitHub-style emoji shortcodes to Unicode.
//!
//! [`lookup`] returns the Unicode codepoint(s) for a `:shortcode:` token so the
//! markdown engine can expand ``:smile:`` inline with zero external assets.
//! Unknown codes pass through unexpanded (the literal `:code:` text), so a
//! colon that happens to surround non-emoji words is never mangled.
//!
//! The table covers the emoji that are both unambiguous and most commonly
//! typed; it is intentionally a curated subset, not the full gemoji catalog.

/// Resolve a shortcode without the surrounding colons, e.g. `"smile"` →
/// `"😄"`. Returns `None` for unknown codes.
pub fn lookup(name: &str) -> Option<&'static str> {
    let key = name.trim();
    EMOJI
        .binary_search_by(|(k, _)| k.cmp(&key))
        .ok()
        .map(|i| EMOJI[i].1)
}

/// Expand a `:code:` token if known; otherwise returns the input unchanged.
pub fn expand(token: &str) -> String {
    let inner = token.trim_start_matches(':').trim_end_matches(':');
    match lookup(inner) {
        Some(u) => u.to_string(),
        None => token.to_string(),
    }
}

